def patch_garmash_featured(html: str) -> tuple[str, bool]:
    if GARMASH_MARKER in html:
        return html, False  # уже применено
    if GARMASH_AWARDS_ANCHOR not in html:
        raise RuntimeError(
            "Не найден якорь featured-карточки Гармаша (Награды) — "
            "структура страницы изменилась."
        )
    new_html = html.replace(
        GARMASH_AWARDS_ANCHOR,
        GARMASH_NEW_PARAGRAPH + GARMASH_AWARDS_ANCHOR,
        1,
    )
    return new_html, True


def patch_clergy_grid(html: str) -> tuple[str, bool]:
    new_inner = build_grid_inner()

    def _repl(m: re.Match[str]) -> str:
        return m.group(1) + new_inner + m.group(3)

    new_html, count = CLERGY_GRID_RE.subn(_repl, html, count=1)
    if count == 0:
        raise RuntimeError(
            "Не найден блок <div class=\"clergy-grid\"> с ожидаемым закрытием. "
            "Проверьте структуру clergy.html."
        )
    return new_html, new_html != html


def main() -> int:
    if not CLERGY_HTML.exists():
        print(f"❌  Не найден файл: {CLERGY_HTML}")
        return 1

    html = CLERGY_HTML.read_text(encoding="utf-8")
    original = html

    html, changed_g = patch_garmash_featured(html)
    if changed_g:
        print("✓ featured: дополнен абзац «День ангела + образование» (Гармаш)")
    else:
        print("· featured: уже актуальный (no-op)")

    html, changed_grid = patch_clergy_grid(html)
    if changed_grid:
        print("✓ grid: пересобран по правке заказчика (Симора добавлена, 5 карточек)")
    else:
        print("· grid: уже актуальный (no-op)")

    if html != original:
        CLERGY_HTML.write_text(html, encoding="utf-8")
        print(f"✓ записано: {CLERGY_HTML.relative_to(ROOT)}")
    else:
        print("· clergy.html без изменений")

    assets_copied = copy_revision_assets()
    if assets_copied:
        print(f"✓ скопировано исходников: {assets_copied}")

    print("\nГотово. Сверьте визуально и закоммитьте.")
    return 0


