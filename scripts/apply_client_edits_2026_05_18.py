def render_facts(facts: list[tuple[str, str]]) -> str:
    """Структурированный блок фактов о клирике — один <p class="clergy-card__bio">."""
    parts = []
    for label, value in facts:
        parts.append(f"<strong>{label}:</strong>&nbsp;{value}")
    return (
        '<p class="clergy-card__bio">\n            '
        + "<br>\n            ".join(parts)
        + "\n          </p>"
    )


def render_card(card: dict) -> str:
    facts_html = render_facts(card["facts"])
    return (
        "      <!-- Card: " + card["key"] + " -->\n"
        '      <article class="clergy-card">\n'
        '        <div class="clergy-card__photo">\n'
        f'          <img class="photo-real" src="{card["photo_src"]}" '
        f'alt="{card["photo_alt"]}" width="350" height="200" loading="lazy" '
        'decoding="async">\n'
        "        </div>\n"
        "        <div>\n"
        f'          <div class="clergy-card__role">{card["role"]}</div>\n'
        f'          <h3 class="clergy-card__name">{card["rank"]}<br>{card["name"]}</h3>\n'
        f"          {facts_html}\n"
        f'          <p class="clergy-card__bio">{card["bio"]}</p>\n'
        "        </div>\n"
        "      </article>\n"
    )


def build_grid_inner() -> str:
    cards_html = "\n".join(render_card(c) for c in CLERGY_CARDS)
    return "\n" + cards_html + "\n    "


