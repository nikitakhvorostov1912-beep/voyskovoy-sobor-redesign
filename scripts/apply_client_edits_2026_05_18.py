def copy_revision_assets() -> int:
    """Кладёт исходники правок в docs/assets/images/source-2026-05-18/."""
    if not REVISIONS_DIR.exists():
        print(f"⚠️  Папка правок не найдена: {REVISIONS_DIR}")
        return 0
    ASSETS_SOURCE_DIR.mkdir(parents=True, exist_ok=True)
    copied = 0
    for src_name, dst_name in ASSETS_TO_COPY:
        src = REVISIONS_DIR / src_name
        dst = ASSETS_SOURCE_DIR / dst_name
        if not src.exists():
            print(f"⚠️  Пропуск (нет файла): {src}")
            continue
        if dst.exists() and dst.stat().st_size == src.stat().st_size:
            continue  # idempotent
        shutil.copy2(src, dst)
        print(f"✓ assets: {dst.relative_to(DOCS)}")
        copied += 1
    return copied


